/* Changer de langue l'écrit tout de suite : le rechargement qui suit doit la
   retrouver. Une langue inconnue retombe sur le français plutôt que de laisser
   le jeu dans un état indéfini. */
function setLangue(l){
  _langue=LANGUES[l]?l:LANGUE_DEFAUT;
  try{ localStorage.setItem(CLE_LANGUE,_langue); }catch(e){}
  return _langue;
}

function _langueInitiale(){
  try{ const s=localStorage.getItem(CLE_LANGUE); if(s&&LANGUES[s])return s; }catch(e){}
  try{
    const n=(navigator&&(navigator.language||navigator.userLanguage))||'';
    if(String(n).slice(0,2).toLowerCase()==='en')return 'en';
  }catch(e){}
  return LANGUE_DEFAUT;
}

/* t('cle', {n:3}) — le texte de la langue courante.

   TROIS REPLIS, dans cet ordre : la langue courante, puis le FRANÇAIS, puis
   une chaîne vide. Jamais le nom de la clé : un `onglet.perso` affiché en
   pleine interface serait pire qu'un mot non traduit. */
function t(cle,vars){
  const table=TEXTES[_langue]||TEXTES[LANGUE_DEFAUT];
  let s=table[cle];
  if(s==null)s=TEXTES[LANGUE_DEFAUT][cle];
  if(s==null)return '';
  if(vars)for(const k in vars)s=s.split('{'+k+'}').join(String(vars[k]));
  /* Une variable non fournie ne doit pas laisser d'accolade à l'écran. */
  return s.replace(/\{[a-z0-9_]+\}/gi,'');
}

/* tOu('cle', repli) — LE DICTIONNAIRE, OU LE TEXTE DÉJÀ ÉCRIT DANS LA DONNÉE.

   Pourquoi t() ne suffit pas. Les 112 quêtes portent leur français DANS
   l'objet (`q.name`, `q.desc`, `q.etapes[].txt`) : c'est de la donnée, lue
   par les outils et les sauvegardes, on ne la vide pas. La traduction se
   superpose donc par clé — et les quêtes non encore traduites doivent rendre
   leur français.

   Or t() renvoie '' sur une clé inconnue, ce qui est le bon choix pour un
   libellé d'interface (mieux vaut un blanc qu'un `onglet.perso` affiché) et
   le pire ici : un panneau de quêtes sans titres. D'où ce second accesseur,
   à n'employer QUE là où un texte de repli existe vraiment. */
function tOu(cle,repli,vars){
  const s=t(cle,vars);
  return s===''?String(repli==null?'':repli):s;
}

